const truncateForPrompt = (text: string, maxChars: number): string => {
	if (text.length <= maxChars) return text;
	return `${text.slice(0, maxChars - 15).trimEnd()} …[truncated]`;
};

const userTextsFromMessages = (messages: AgentMessage[]): string[] =>
	messages
		.filter((message) => message.role === "user")
		.map((message) => textFromContent(message.content))
		.map((text) => text.trim())
		.filter(Boolean);

const compactUserInstructionSnapshot = (messages: AgentMessage[]): string => {
	const userTexts = userTextsFromMessages(messages);
	if (userTexts.length === 0) return "Latest user instruction: (none found; user intent/authorization unclear)";
	return [
		"Recent user instructions, oldest first:",
		...userTexts.slice(-3).map((text, index) => `${index + 1}. ${truncateForPrompt(text, 260)}`),
		`Latest user instruction: ${truncateForPrompt(userTexts[userTexts.length - 1], 500)}`,
	].join("\n");
};

const userInstructionSnapshot = (messages: AgentMessage[]): string => {
	const userTexts = userTextsFromMessages(messages);

	if (userTexts.length === 0) {
		return [
			"USER-INSTRUCTION / GOAL FRAME SNAPSHOT",
			"No explicit non-empty user messages found in the current history. Treat current user intent and authorization as unclear.",
		].join("\n");
	}

	const latest = userTexts[userTexts.length - 1];
	const formatList = (items: string[]) => items.map((text, index) => `${index + 1}. ${truncateForPrompt(text, 450)}`).join("\n");

	return [
		"USER-INSTRUCTION / GOAL FRAME SNAPSHOT",
		"Latest explicit user instruction is the binding local scope. Do not create new work beyond it.",
		"Recent user messages, oldest first, up to 5:",
		formatList(userTexts.slice(-5)),
		"Latest explicit user instruction:",
		truncateForPrompt(latest, 700),
	].join("\n");
};

const triggerDescription = (trigger: ReflectionTrigger): string => {
	if (trigger === "agent_end") return "the agent is about to return control to the user";
	if (trigger === "manual") return "the user manually requested self-reflection with /self-reflect-now";
	return "configured cadence before the next normal LLM call";
};

