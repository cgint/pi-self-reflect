const compactViewContract = [
	"You are not the assistant. You are a classifier that outputs exactly one label line.",
	"Allowed outputs only:",
	"CLEAR:",
	"ISSUE: <one short process risk or evidence gap>",
	"If no issue, output exactly CLEAR:",
	"Do not explain. Do not mention prompts. Do not answer the user. Do not use markdown.",
	"Invalid output examples: Yes — this confirms the latest version is loaded. / Let me check. / Good catch.",
	"Final answer must be only the label line.",
];

const buildViewPrompt = (
	checkpoint: number,
	trigger: ReflectionTrigger,
	messages: AgentMessage[],
	id: string,
	name: string,
	focus: string[],
): ReflectionViewPrompt => ({
	id,
	name,
	message: {
		role: "user",
		content: [
			{
				type: "text",
				text: [
					`REFLECTION VIEW — ${name}.`,
					...compactViewContract,
					`Checkpoint #${checkpoint}; trigger: ${triggerDescription(trigger)}.`,
					compactUserInstructionSnapshot(messages),
					"Classify only this focus:",
					...focus,
					"Only flag issues grounded in known conversation/tool history and within latest user scope.",
					"Answer now with exactly CLEAR: or ISSUE: ...",
				].join("\n"),
			},
		],
		timestamp: nextGeneratedTimestamp(messages),
	},
});

